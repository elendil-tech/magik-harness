const example = analyseRoot(LEDGERLY);
const PRODUCT_WIDE = VIEW_IDS.filter((id) => !RENDERERS[id].required);

/** Every fenced block of a language in a Markdown text. */
const fences = (text, lang) => [...text.matchAll(new RegExp("```" + lang + "\\n([\\s\\S]*?)```", "g"))].map((m) => m[1]);

/** The cells of the Markdown table that follows `heading`, as rows of strings. */
function tableAfter(text, heading) {
  const lines = text.split("\n");
  const at = lines.findIndex((l) => l.trim() === heading);
  assert.ok(at >= 0, `no heading ${heading}`);
  const rows = [];
  for (let i = at + 1; i < lines.length; i++) {
    if (lines[i].startsWith("|")) rows.push(lines[i].split(/(?<!\\)\|/).slice(1, -1).map((c) => c.trim()));
    else if (rows.length) break;
  }
  return rows.slice(2); // drop the header and the rule under it
}

/** Every relative Markdown link in every file of a folder that does not lead anywhere. */
function brokenLinks(dir) {
  const broken = [];
  let total = 0;
  for (const rel of listFiles(dir).filter((f) => f.endsWith(".md"))) {
    const file = join(dir, rel);
    for (const m of readFileSync(file, "utf8").matchAll(/\]\(([^)#\s]+)(?:#[^)]*)?\)/g)) {
      if (/^[a-z][a-z0-9+.-]*:/i.test(m[1])) continue;
      total++;
      if (!existsSync(resolve(dirname(file), m[1]))) broken.push(`${rel} -> ${m[1]}`);
    }
  }
  return { broken, total };
}

describe("the views as a set", () => {
  test("every declared view has a renderer, and every renderer is declared", () => {
    assert.deepEqual([...meta.views.keys()].sort(), [...VIEW_IDS].sort());
    for (const [id, v] of meta.views) {
      assert.ok(v.title && v.answers && v.scope, `${id} says what it is and what question it answers`);
    }
  });

  test("a view that takes no target and one that needs one are declared as such", () => {
    assert.equal(RENDERERS.spec.required, true);
    assert.equal(RENDERERS.card.required, true);
    for (const id of ["context", "touchpoints", "permissions", "crud", "entitlements", "coverage", "obligations", "events"]) assert.equal(RENDERERS[id].none, true, `${id} covers the whole product`);
  });

  for (const id of PRODUCT_WIDE) {
    test(`${id} renders on the worked example without gaps in its own text`, () => {
      const text = renderView(example, id);
      assert.ok(text.endsWith("\n") && !text.endsWith("\n\n"), "ends with exactly one newline");
      assert.ok(text.trim().length > 40, "says something");
      assert.ok(text.startsWith("# "), "starts with a title");
      for (const bad of ["undefined", "[object Object]", "NaN", "Infinity"]) assert.ok(!text.includes(bad), `no ${bad}`);
      assert.ok(!/\n{3,}/.test(text), "no runs of blank lines");
      assert.ok(!/[ \t]+\n/.test(text), "no trailing spaces");
    });
  }

  test("rendering twice gives the same text: a view is a function of the records", () => {
    for (const id of PRODUCT_WIDE) assert.equal(renderView(example, id), renderView(example, id), id);
    assert.equal(renderView(example, "spec", "FEAT-send-invoice"), renderView(example, "spec", "FEAT-send-invoice"));
  });

  test("the banner is added only when asked for, and says how to regenerate", () => {
    const plain = renderView(example, "coverage");
    const banner = renderView(example, "coverage", undefined, { banner: true });
    assert.ok(!plain.includes("Generated by pds"));
    assert.ok(banner.startsWith(BANNER("coverage")));
    assert.match(BANNER("spec", "FEAT-x"), /^<!-- Generated by pds \(spec FEAT-x\)\. Do not edit: change the records and regenerate\. -->\n\n$/);
    assert.equal(banner.slice(BANNER("coverage").length), plain);
  });

  test("a view fails with something to act on when it is pointed at the wrong thing", () => {
    assert.throws(() => renderView(example, "nope"), (e) => e instanceof ViewError && /no view nope; the views are: product-map/.test(e.message));
    assert.throws(() => renderView(example, "spec"), /spec needs an element: pds view spec /);
    assert.throws(() => renderView(example, "spec", "FEAT-send-invoic"), /no element FEAT-send-invoic; did you mean FEAT-send-invoice\?/);
    assert.throws(() => renderView(example, "spec", "ENT-invoice"), /spec is for FEAT or CAP; ENT-invoice is a ENT/);
    assert.throws(() => renderView(example, "journey", "FEAT-send-invoice"), /journey is for JRN/);
    assert.throws(() => renderView(example, "permissions", "FEAT-send-invoice"), /permissions covers the whole product and takes no target/);
  });
});

describe("what pds views writes", () => {
  const files = plan(example);

  test("one file per product-wide view, a specification for each feature and capability, and an index", () => {
    const names = [...files.keys()];
    for (const id of PRODUCT_WIDE) assert.ok(files.has(`${id}.md`), id);
    const owners = example.model.all(["CAP", "FEAT"]);
    for (const e of owners) assert.ok(files.has(`specs/${e.id}.md`), e.id);
    assert.equal(names.length, PRODUCT_WIDE.length + owners.length + 1, "and nothing else");
    assert.ok(files.has("README.md"));
    assert.equal(names.length, 70, "the worked example: 21 views, 46 capabilities, 4 features, the index... minus the two kinds that are written per element");
  });

  test("every file carries the banner, so that a later run knows what it may replace", () => {
    for (const [name, text] of files) assert.ok(text.startsWith("<!-- Generated by pds"), name);
  });

  test("the index names every view and every specification", () => {
    const index = files.get("README.md");
    for (const id of PRODUCT_WIDE) assert.ok(index.includes(`(${id}.md)`), id);
    for (const e of example.model.all(["CAP", "FEAT"])) assert.ok(index.includes(`(specs/${e.id}.md)`), e.id);
  });

  test("a retired feature or capability is not given a specification", () => {
    const root = copyExample();
    editFront(root, "FEAT-pay-invoice-online", (f) => (f.lifecycle = "retired"));
    const a = analyseRoot(root);
    assert.ok(!plan(a).has("specs/FEAT-pay-invoice-online.md"));
    assert.ok(plan(a).has("specs/FEAT-send-invoice.md"));
  });

  test("every relative link in every generated file leads somewhere", async () => {
    const root = copyExample();
    assert.equal((await pds(["views"], { cwd: root })).code, 0);
    const { broken, total } = brokenLinks(join(root, "views"));
    assert.ok(total > 300, `the example has plenty of links to check (${total})`);
    assert.deepEqual(broken, []);
  });

  test("links follow a views_dir that is deeper than the default", async () => {
    const root = copyExample();
    const cfg = join(root, "pds.yaml");
    writeFileSync(cfg, readFileSync(cfg, "utf8").replace(/^views_dir:.*\n/m, "") + "views_dir: build/generated/views\n");
    assert.equal((await pds(["views"], { cwd: root })).code, 0);
    assert.ok(existsSync(join(root, "build/generated/views/specs/FEAT-send-invoice.md")));
    const { broken, total } = brokenLinks(join(root, "build/generated/views"));
    assert.ok(total > 300);
    assert.deepEqual(broken, []);
    assert.ok(readFileSync(join(root, "build/generated/views/product-map.md"), "utf8").includes("](../../../definition/"));
    assert.ok(readFileSync(join(root, "build/generated/views/specs/FEAT-send-invoice.md"), "utf8").includes("](../../../../definition/"));
  });

  test("links follow --out, wherever it points", async () => {
    const root = copyExample();
    for (const out of ["somewhere/else", "a/b/c/d"]) {
      assert.equal((await pds(["views", "--out", out], { cwd: root })).code, 0);
      const { broken, total } = brokenLinks(join(root, out));
      assert.ok(total > 300, out);
      assert.deepEqual(broken, [], out);
    }
    assert.equal((await pds(["spec", "FEAT-send-invoice", "--out", "notes/deep/er/spec.md"], { cwd: root })).code, 0);
    assert.deepEqual(brokenLinks(join(root, "notes/deep/er")).broken, []);
    assert.equal((await pds(["view", "trace", "--out", "trace.md"], { cwd: root })).code, 0, "a file in the project root itself");
    assert.ok(readFileSync(join(root, "trace.md"), "utf8").includes("](definition/"));
    assert.deepEqual(brokenLinks(root).broken.filter((b) => b.startsWith("trace.md")), []);
  });
});

describe("pds views and pds view", () => {
  test("is idempotent, and --check says so without writing anything", async () => {
    const root = copyExample();
    const first = await pds(["views"], { cwd: root });
    assert.equal(first.code, 0);
    assert.match(first.out, /70 view files in views\/: 0 written, 70 unchanged\./);
    const before = snapshot(root);
    const check = await pds(["views", "--check"], { cwd: root });
    assert.equal(check.code, 0);
    assert.match(check.out, /The 70 generated views are up to date\./);
    assert.deepEqual([...snapshot(root)], [...before]);
  });

  test("--check fails, and names what differs, when a record has changed", async () => {
    const root = copyExample();
    editFront(root, "FEAT-send-invoice", (f) => (f.title = "Send an invoice to a client"));
    const before = snapshot(root);
    const check = await pds(["views", "--check"], { cwd: root });
    assert.equal(check.code, 1);
    assert.match(check.out, /The generated views are out of date: \d+ files differ, 0 stale files\./);
    assert.match(check.out, /changed  product-map\.md/);
    assert.match(check.out, /\.\.\. and 5 more/, "a long list says it is long rather than quietly stopping");
    assert.match(check.out, /Run: pds views/);
    assert.deepEqual([...snapshot(root)], [...before], "--check never writes");
    const fix = await pds(["views"], { cwd: root });
    assert.equal(fix.code, 0);
    assert.equal((await pds(["views", "--check"], { cwd: root })).code, 0);
  });

  test("removes a generated file that no longer corresponds to anything, and never touches one a person wrote", async () => {
    const root = copyExample();
    await pds(["views"], { cwd: root });
    writeFileSync(join(root, "views/specs/FEAT-gone.md"), BANNER("spec", "FEAT-gone") + "# An old spec\n");
    writeFileSync(join(root, "views/my-notes.md"), "# My notes\n\nWritten by hand.\n");
    writeFileSync(join(root, "views/specs/by-hand.md"), "# A page I wrote\n");
    const check = await pds(["views", "--check"], { cwd: root });
    assert.equal(check.code, 1);
    assert.match(check.out, /1 stale file/);
    assert.match(check.out, /stale    specs\/FEAT-gone\.md/);
    const run = await pds(["views"], { cwd: root });
    assert.match(run.out, /1 stale removed/);
    assert.ok(!existsSync(join(root, "views/specs/FEAT-gone.md")));
    assert.equal(readFileSync(join(root, "views/my-notes.md"), "utf8"), "# My notes\n\nWritten by hand.\n");
    assert.equal(readFileSync(join(root, "views/specs/by-hand.md"), "utf8"), "# A page I wrote\n");
  });

  test("when an element is retired its specification goes with it", async () => {
    const root = copyExample();
    await pds(["views"], { cwd: root });
    assert.ok(existsSync(join(root, "views/specs/FEAT-pay-invoice-online.md")));
    editFront(root, "FEAT-pay-invoice-online", (f) => (f.lifecycle = "retired"));
    const run = await pds(["views"], { cwd: root });
    assert.match(run.out, /1 stale removed/);
    assert.ok(!existsSync(join(root, "views/specs/FEAT-pay-invoice-online.md")));
  });

  test("lists the views, prints one without a banner, and writes one with --out", async () => {
    const list = await pds(["view"], { cwd: LEDGERLY });
    assert.equal(list.code, 0);
    for (const id of VIEW_IDS) assert.ok(list.out.includes(`  ${id}`), id);
    const one = await pds(["view", "flow", "FLW-send-invoice"], { cwd: LEDGERLY });
    assert.equal(one.code, 0);
    assert.ok(one.out.startsWith("# "), "printed views have no banner");
    assert.ok(one.out.includes("```mermaid\nflowchart"));
    const root = copyExample();
    const wrote = await pds(["view", "flow", "FLW-send-invoice", "--out", "x/flow.md"], { cwd: root });
    assert.equal(wrote.code, 0);
    assert.equal(wrote.out.trim(), "Wrote x/flow.md");
    const file = readFileSync(join(root, "x/flow.md"), "utf8");
    assert.ok(file.startsWith("# "), "a single view written to a file has no banner either: it is yours to keep");
    assert.ok(file.includes("```mermaid\nflowchart"));
    assert.deepEqual(brokenLinks(join(root, "x")).broken, [], "and its links are made from where it was written");
  });

  test("an out path that climbs out of the folder is reported in full", async () => {
    const root = copyExample();
    const dir = scratch("pds-out-");
    const target = join(dir, "spec.md");
    const wrote = await pds(["spec", "FEAT-send-invoice", "--out", target], { cwd: root });
    assert.equal(wrote.out.trim(), `Wrote ${target}`);
    assert.ok(existsSync(target));
  });

  test("suggests the nearest view and refuses a target it cannot use", async () => {
    const typo = await pds(["view", "flwo"], { cwd: LEDGERLY });
    assert.equal(typo.code, 2);
    assert.match(typo.err, /no view flwo; did you mean flow\?/);
    assert.equal((await pds(["view", "coverage", "FEAT-send-invoice"], { cwd: LEDGERLY })).code, 2);
    assert.equal((await pds(["view", "card"], { cwd: LEDGERLY })).code, 2);
    assert.equal((await pds(["spec"], { cwd: LEDGERLY })).code, 2);
  });
});

describe("Mermaid", () => {
  const kinds = new Set(["flowchart", "stateDiagram-v2", "erDiagram", "journey"]);
  const all = new Map([...plan(example)].filter(([name]) => name.endsWith(".md")));

  test("every diagram in every generated file opens with a diagram type Mermaid knows, and every fence closes", () => {
    let diagrams = 0;
    for (const [name, text] of all) {
      assert.equal((text.match(/^```/gm) || []).length % 2, 0, `${name}: fences balance`);
      for (const body of fences(text, "mermaid")) {
        diagrams++;
        const first = body.split("\n").find((l) => l.trim());
        assert.ok(kinds.has(first.trim().split(/\s/)[0]), `${name}: ${first}`);
      }
    }
    assert.ok(diagrams >= 20, `the example has diagrams to check (${diagrams})`);
  });

  test("no diagram contains a character that breaks a label", () => {
    for (const [name, text] of all) {
      for (const body of fences(text, "mermaid")) {
        for (const label of body.matchAll(/"([^"]*)"/g)) {
          assert.ok(!/[<>&]/.test(label[1].replace(/<br\/>/g, "").replace(/#(?:amp|lt|gt|quot);/g, "")), `${name}: ${label[1]}`);
        }
      }
    }
  });

  test("a flowchart's node ids are unique, and never a word Mermaid reserves", () => {
    const reserved = new Set(["end", "graph", "subgraph", "class", "classDef", "style", "click", "default", "direction", "flowchart", "linkStyle"]);
    for (const [name, text] of all) {
      for (const body of fences(text, "mermaid").filter((b) => b.startsWith("flowchart"))) {
        const ids = [...body.matchAll(/^\s+([A-Za-z0-9_]+)(?:\[|\(|\{|\s*-->|\s*-\.|\s*==)/gm)].map((m) => m[1]);
        for (const id of ids) assert.ok(!reserved.has(id), `${name}: ${id}`);
        const declared = [...body.matchAll(/^\s+([A-Za-z0-9_]+)(?:\[\[|\[\(|\[|\(\(|\(|\{)/gm)].map((m) => m[1]);
        assert.equal(new Set(declared).size, declared.length, `${name}: a node declared twice`);
      }
    }
  });

  test("the helpers keep user text inside a label and user ids out of the grammar", () => {
    assert.equal(q('Pay "now" & <later>'), "Pay #quot;now#quot; #amp; #lt;later#gt;");
    assert.equal(q("  many   spaces\nand lines "), "many spaces and lines");
    assert.equal(q("a short one", 40), "a short one");
    assert.equal(q("one two three four five six", 10), "one two<br/>three four<br/>five six");
    assert.equal(q(undefined), "");
    assert.equal(mid("n", "FEAT-end"), "nFEAT_end");
    assert.equal(mid("s", "STM-a.b c"), "sSTM_a_b_c");
    assert.deepEqual(wrapWords("aaa bbb ccc", 7), ["aaa bbb", "ccc"]);
    assert.deepEqual(wrapWords("", 7), []);
  });

  test("tables escape pipes and newlines in cells, and say so when empty", () => {
    assert.equal(table(["A", "B"], []), "_None._\n");
    assert.equal(table(["A", "B"], [["x|y", "line\nbreak"], [null, undefined]]), "| A | B |\n| --- | --- |\n| x\\|y | line break |\n|  |  |\n");
  });

  test("a record whose slug is a Mermaid keyword still draws", async () => {
    const root = copyExample();
    addRecord(root, "ENT-class", { title: "Class", maturity: "stub", anchor: "DOM-invoicing", origin: "human" });
    addRecord(root, "ENT-end", { title: "End", maturity: "stub", anchor: "DOM-invoicing", origin: "human" });
    const a = analyseRoot(root);
    const er = renderView(a, "er");
    assert.ok(/^  CLASS$/m.test(er) && /^  END$/m.test(er), "entities are named in capitals, which Mermaid never reads as keywords");
    for (const id of PRODUCT_WIDE) assert.doesNotThrow(() => renderView(a, id), id);
  });
});

