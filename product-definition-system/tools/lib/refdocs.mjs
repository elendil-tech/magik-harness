// The reference documentation, generated from the meta-model. Nothing here is
// written by hand and no number is typed in: counts and tables are computed, so
// the reference cannot disagree with the data it describes. `pds docs --check`
// fails when the committed files are out of date.
import { table } from "./views/util.mjs";
import { fieldHint } from "./templates.mjs";

const BANNER = "<!-- Generated by `pds docs` from meta-model/. Do not edit: change the meta-model and regenerate. -->\n\n";
const list = (v) => [].concat(v ?? []);
const code = (xs) => list(xs).map((x) => `\`${x}\``).join(", ");

/** One atom of a rule's requirement, in words. */
export function describeAtom(a) {
  if (!a || typeof a !== "object") return String(a);
  if (a.all) return a.all.map(describeAtom).join(" and ");
  if (a.any) return `(${a.any.map(describeAtom).join(" or ")})`;
  if (a.not) return `not (${describeAtom(a.not)})`;
  if (a.field) {
    const m = [a.equals !== undefined ? `equals ${JSON.stringify(a.equals)}` : null, a.one_of ? `is one of ${a.one_of.join(", ")}` : null, a.min_items ? `has at least ${a.min_items} items` : null].filter(Boolean);
    return `field \`${a.field}\`${m.length ? " " + m.join(", ") : ""}`;
  }
  if (a.section) return `section “${a.section}”${a.min_words ? ` of at least ${a.min_words} words` : ""}`;
  if (a.block) return `block \`${a.block}\``;
  if (a.facet) return `facet \`${a.facet}\``;
  const edge = (x, dir) => {
    const n = x.min ?? 1;
    const bits = [`${x.max !== undefined ? `${n} to ${x.max}` : `at least ${n}`} ${dir} \`${x.rel}\``];
    if (x.to || x.from) bits.push(`${dir === "outgoing" ? "to" : "from"} ${code(x.to || x.from)}`);
    if (x.include && x.include !== "self") bits.push(`counting ${x.include}`);
    if (x.attr) bits.push(`with ${JSON.stringify(x.attr)}`);
    if (x.where) bits.push(`where ${JSON.stringify(x.where)}`);
    return bits.join(" ");
  };
  if (a.out) return edge(a.out, "outgoing");
  if (a.in) return edge(a.in, "incoming");
  if (a.children) {
    const c = a.children;
    const n = c.min ?? 1;
    return `${c.max !== undefined ? `${n} to ${c.max}` : `at least ${n}`} ${code(c.type)} anchored on it${c.where ? ` where ${JSON.stringify(c.where)}` : ""}`;
  }
  return JSON.stringify(a);
}

function describeApplies(a = {}) {
  return [a.tiers ? `tiers ${a.tiers.join(", ")}` : null, a.where ? `where ${JSON.stringify(a.where)}` : null, a.facet ? `facet ${list(a.facet).join(" and ")}` : null, a.not_facet ? `not facet ${list(a.not_facet).join(", ")}` : null, a.anchor ? `anchored on ${list(a.anchor).join(" or ")}` : null, a.module ? `module ${a.module}` : null, a.unless ? `unless ${JSON.stringify(a.unless)}` : null].filter(Boolean).join("; ");
}

/** When a probe applies, in words: "tiers 1, 2; facets handles_pii". Used by the reference and by `pds explain`. */
export function describeProbeApplies(a = {}) {
  return [`tiers ${(a.tiers || [1, 2]).join(", ")}`, a.kind ? `kind ${a.kind.join(" or ")}` : null, a.facet ? `facets ${a.facet.join(" and ")}` : null, a.any_facet ? `any of ${a.any_facet.join(", ")}` : null, a.not_facet ? `not ${a.not_facet.join(", ")}` : null].filter(Boolean).join("; ");
}

// ------------------------------------------------------------------ the files

function overview(meta) {
  const coverage = meta.rules.length;
  const generated = meta.implicitRules.length;
  const byClass = (c) => meta.checks.filter((x) => x.class === c).length;
  const byAdoption = meta.model.adoption.ladder.map((l) => [l, [...meta.types.values()].filter((t) => t.adoption === l).length]);
  return [
    "# Reference\n",
    "Generated from the meta-model in `meta-model/`. The counts and tables below are computed, never typed.\n",
    table(["", "Count"], [
      ["Element types", meta.types.size],
      ["Families", Object.keys(meta.families).length],
      ["Relation types", meta.relations.size],
      ["Coverage rules written by hand", coverage],
      ["Coverage rules generated from element types", generated],
      ["Concern probes", meta.probes.length],
      ["Coded checks", `${meta.checks.length} (${["SCH", "REF", "INT", "QLT", "GOV", "PRB"].map((c) => `${c} ${byClass(c)}`).join(", ")})`],
      ["Gates", meta.gates.length],
      ["Views", meta.views.size],
      ["Modules", Object.keys(meta.modules).length],
      ["Profiles", Object.keys(meta.profiles).length],
    ]),
    "## Maturity ladder\n",
    table(["Rung", "Meaning"], meta.ladder.map((r) => [`\`${r}\``, meta.model.maturity.rungs[r]])),
    "## Tiers\n",
    table(["Tier", "Name", "Review every", "Test"], Object.entries(meta.tiers).map(([t, v]) => [t, v.name, `${v.review_every_days} days`, v.test])),
    "## Statuses that are not maturity\n",
    table(["Dimension", "Values", "Meaning"], [
      ["Approval", code(meta.model.approval), "Authority. Bound to a hash of the content; only named human approvers."],
      ["Lifecycle", code(meta.model.lifecycle), "Place in the product's life. Retired elements are kept and excluded from coverage."],
      ["Origin", code(meta.model.origin), "Where it came from. Skeleton elements are prompts nobody has confirmed."],
    ]),
    "## Adoption levels\n",
    table(["Level", "Types", "Adds"], byAdoption.map(([l, n]) => [`\`${l}\``, n, meta.model.adoption.levels[l]])),
    "## The spine\n",
    table(["Zoom", "Type", "Question"], [...meta.spine.map((s) => [s.zoom, `\`${s.type}\` ${s.name}`, s.question]), [meta.model.satellite_zoom, "satellites", "Everything anchored on a feature: flows, screens, rules, requirements, tests."]]),
    "## Files\n",
    ["- [element-types.md](element-types.md)", "- [relations.md](relations.md)", "- [rules.md](rules.md)", "- [probes.md](probes.md)", "- [views.md](views.md)", "- [modules.md](modules.md)", "- [skeleton.md](skeleton.md)"].join("\n") + "\n",
  ].join("\n");
}

function elementTypes(meta) {
  const out = ["# Element types\n", "Each type has a home on the spine (its `anchors`), the fields, sections and structured blocks it needs, and the rung from which each is required. Fields marked `optional` are never required. Every record also carries the envelope: " + code(Object.keys(meta.envelope)) + ".\n"];
  for (const [fid, f] of Object.entries(meta.families)) {
    const types = [...meta.types.values()].filter((t) => t.family === fid);
    if (!types.length) continue;
    out.push(`## ${f.title}\n`, `_${f.question}_\n`);
    for (const t of types) {
      out.push(`### \`${t.code}\` ${t.name}\n`, t.summary + "\n", `Adoption: \`${t.adoption}\`. Lives under: ${t.anchors.length ? code(t.anchors) : "nothing: it is the root"}.${t.singleton ? " One per product." : ""}\n`);
      const rows = Object.entries(t.fields).map(([n, s]) => [`\`${n}\``, s.type, fieldHint(s), s.required_at ? `\`${s.required_at}\`` : "optional", s.doc || ""]);
      if (rows.length) out.push("**Fields**\n", table(["Field", "Type", "Takes", "Needed for", "Meaning"], rows));
      if (t.sections.length) out.push("**Sections**\n", table(["Heading", "Needed for", "Tiers", "The question it answers"], t.sections.map((s) => [s.heading, s.required_at ? `\`${s.required_at}\`` : "optional", s.tiers ? s.tiers.join(", ") : "all", s.ask])));
      const blocks = Object.entries(t.blocks || {});
      if (blocks.length) out.push("**Structured blocks**\n", table(["Block", "Needed for", "Contents"], blocks.map(([n, b]) => [`\`${n}\``, `\`${b.required_at}\`${b.unless ? ` unless ${JSON.stringify(b.unless)}` : ""}`, b.doc])));
    }
  }
  return out.join("\n");
}

function relations(meta) {
  const rows = [...meta.relations.values()].map((r) => [`\`${r.name}\``, `\`${r.inverse}\``, r.allow.map((p) => `${code(p.from)} → ${code(p.to)}`).join("<br>"), r.attrs ? Object.keys(r.attrs).map((a) => `\`${a}\``).join(", ") : "", `${r.impacts.to} / ${r.impacts.from}`, r.doc]);
  return [
    "# Relation types\n",
    "A relation is stored once, on the element it leaves, under `rel` (or implied by a structured block or reference field). The inverse is derived. **Impact** reads: how strongly the target is affected when the source changes / how strongly the source is affected when the target changes. `strong` means must be reviewed, `weak` should be reviewed.\n",
    `Impact walks follow strong edges up to ${meta.impactConfig.strong_hops} hops and weak edges up to ${meta.impactConfig.weak_hops}. The spine carries impact too: a change flows ${meta.impactConfig.anchor.down} from an element to what is anchored on it, and ${meta.impactConfig.anchor.up} the other way.\n`,
    table(["Relation", "Read backwards", "Allowed", "Attributes", "Impact", "Meaning"], rows),
  ].join("\n");
}

function rules(meta) {
  const out = ["# Rules, checks and gates\n"];
  out.push("## Maturity\n", "An element's supported rung is the highest one for which every `error` rule from that rung down holds, capped by the gates. A claim above that is an error.\n");
  const byType = new Map();
  for (const r of meta.rules) {
    for (const t of list(r.applies.type)) {
      if (!byType.has(t)) byType.set(t, []);
      byType.get(t).push(r);
    }
  }
  out.push("## Coverage rules written by hand\n");
  for (const [t, rs] of [...byType].sort(([a], [b]) => a.localeCompare(b))) {
    out.push(`### \`${t}\`\n`, table(["Rule", "From", "Severity", "Requires", "When it fails", "Conditions"], rs.map((r) => [`\`${r.id}\``, `\`${r.applies.from}\``, r.sev || "error", describeAtom(r.require), r.msg, describeApplies(r.applies)])));
  }
  const gen = new Map();
  for (const r of meta.implicitRules) {
    const t = r.applies.type;
    gen.set(t, (gen.get(t) || 0) + 1);
  }
  out.push("## Coverage rules generated from element types\n", "Every field, section and block with a `required_at` in `element-types.yaml` becomes a rule named `FLD-TYPE-field`, `SEC-TYPE-heading` or `BLK-TYPE-block`. They are not listed one by one; `pds explain TYPE` shows them with the type.\n", table(["Type", "Generated rules"], [...gen].sort(([a], [b]) => String(a).localeCompare(String(b))).map(([t, n]) => [t === "*" ? "every type (envelope)" : `\`${t}\``, n])));
  out.push("## Checks\n", "Coded checks for what a declarative rule cannot say. `from` is the rung an element must claim before the check applies to it.\n");
  for (const c of ["SCH", "REF", "INT", "QLT", "GOV", "PRB"]) {
    const cs = meta.checks.filter((x) => x.class === c);
    out.push(`### ${c}\n`, table(["Check", "Severity", "From", "Reads", "What it checks"], cs.map((x) => [`\`${x.id}\``, x.sev, x.from ? `\`${x.from}\`` : "any", code(x.uses || []), x.doc])));
  }
  out.push("## Gates\n", table(["Gate", "Caps at", "Meaning"], meta.gates.map((g) => [`\`${g.id}\``, `\`${g.caps_at}\``, g.doc])));
  return out.join("\n");
}

function probes(meta) {
  return [
    "# Concern probes\n",
    "A probe is a concern that is easy to forget and expensive to forget late. Each applicable probe has to be answered on the feature as `addressed` (pointing at the elements that deal with it), `na` (with the reason) or `deferred` (with a reason and a date). Silence blocks `specified`.\n",
    table(["Probe", "Module", "Applies to", "Counts as addressed by", "The question"], meta.probes.map((p) => [`\`${p.id}\` ${p.title}`, p.module || "core", describeProbeApplies(p.applies), code(p.addressed_by || []) || "anything", p.ask])),
  ].join("\n");
}

function views(meta) {
  return [
    "# Views\n",
    "A view is generated from the definition and never edited. `pds view NAME [ID]` prints one; `pds views` writes them all.\n",
    table(["View", "Title", "Answers", "Pointed at", "Form", "Reads"], [...meta.views].map(([id, v]) => [`\`${id}\``, v.title, v.answers, v.scope, v.form, code(v.uses || []) || "the elements"])),
  ].join("\n");
}

function modules(meta) {
  const used = (m) => ({
    probes: meta.probes.filter((p) => (p.module || "core") === m).length,
    rules: meta.rules.filter((r) => (r.applies.module || "core") === m).length,
    seeds: Object.values(meta.profiles).reduce((n, p) => n + (meta.patterns(p.id)?.seeds || []).filter((s) => (s.module || "core") === m).length, 0),
  });
  return [
    "# Modules and profiles\n",
    "A module switches on rules and probes that only matter for some products. A profile chooses the modules and the starting skeleton.\n",
    table(["Module", "Meaning", "Probes", "Rules", "Skeleton records"], Object.entries(meta.modules).map(([m, v]) => [`\`${m}\``, v.doc, used(m).probes, used(m).rules, used(m).seeds])),
    "## Profiles\n",
    table(["Profile", "Adoption", "Modules", "About"], Object.values(meta.profiles).map((p) => [`\`${p.id}\``, `\`${p.defaults.adoption}\``, code(p.defaults.modules), p.doc])),
  ].join("\n");
}

function skeleton(meta) {
  const out = ["# The starting skeleton\n", "What `pds init` writes for each profile. Every record is a stub with `origin: skeleton`: a prompt to confirm, correct or delete, capped at `outlined` until a person does.\n"];
  for (const p of Object.values(meta.profiles)) {
    const patterns = meta.patterns(p.id);
    if (!patterns) continue;
    const seeds = patterns.seeds;
    const byType = new Map();
    for (const s of seeds) byType.set(meta.typeOfId(s.id), (byType.get(meta.typeOfId(s.id)) || 0) + 1);
    out.push(`## ${p.title} (\`${p.id}\`)\n`, `${seeds.length} seeds: ${[...byType].map(([t, n]) => `${n} ${t}`).join(", ")}.\n`);
    const doms = seeds.filter((s) => s.id.startsWith("DOM-"));
    const rows = doms.map((d) => [`\`${d.id}\` ${d.title}`, d.module || "core", seeds.filter((s) => s.anchor === d.id && s.id.startsWith("CAP-")).map((c) => c.title).join("; "), d.note || ""]);
    out.push("### Domains and capabilities\n", table(["Domain", "Module", "Capabilities", "Note"], rows));
    const questions = seeds.filter((s) => s.id.startsWith("QST-"));
    out.push("### Foundational questions\n", table(["Question", "Module", "Blocking"], questions.map((q) => [q.title, q.module || "core", q.fields?.blocking ? "yes" : "no"])));
  }
  return out.join("\n");
}

/** Every reference file: name to text. */
export function generateReference(meta) {
  const files = {
    "README.md": overview(meta),
    "element-types.md": elementTypes(meta),
    "relations.md": relations(meta),
    "rules.md": rules(meta),
    "probes.md": probes(meta),
    "views.md": views(meta),
    "modules.md": modules(meta),
    "skeleton.md": skeleton(meta),
  };
  return new Map(Object.entries(files).map(([k, v]) => [k, BANNER + v.replace(/\n{3,}/g, "\n\n").trimEnd() + "\n"]));
}
