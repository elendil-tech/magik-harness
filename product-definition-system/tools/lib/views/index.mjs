// The view registry. A view is a pure function of the analysis: it never reads
// the disk and never changes the definition, so the same records always give
// the same output.
import { bind } from "./util.mjs";
import { renderFlow, renderState, renderEr, renderContext, renderJourney, renderScreens, renderDeps } from "./diagrams.mjs";
import { renderPermissions, renderCrud, renderEntitlements, renderEvents, renderTouchpoints } from "./matrices.mjs";
import { renderProductMap, renderCard, renderSpec, renderTrace, renderRegisters, renderGlossary, renderObligations, renderRelease, renderCoverage } from "./documents.mjs";
import { suggest } from "../checks/refs.mjs";

export { computeStats } from "./documents.mjs";

export class ViewError extends Error {}

/** One renderer per declared view, and what each accepts as its target. */
export const RENDERERS = {
  "product-map": { fn: renderProductMap },
  card: { fn: renderCard, required: true },
  spec: { fn: renderSpec, required: true, types: ["FEAT", "CAP"] },
  flow: { fn: renderFlow },
  state: { fn: renderState },
  er: { fn: renderEr },
  context: { fn: renderContext, none: true },
  journey: { fn: renderJourney, types: ["JRN"] },
  screens: { fn: renderScreens },
  touchpoints: { fn: renderTouchpoints, none: true },
  permissions: { fn: renderPermissions, none: true },
  crud: { fn: renderCrud, none: true },
  entitlements: { fn: renderEntitlements, none: true },
  trace: { fn: renderTrace },
  registers: { fn: renderRegisters },
  glossary: { fn: renderGlossary },
  coverage: { fn: renderCoverage, none: true },
  deps: { fn: renderDeps },
  release: { fn: renderRelease, types: ["RLS"] },
  obligations: { fn: renderObligations, none: true },
  events: { fn: renderEvents, none: true },
};

export const VIEW_IDS = Object.keys(RENDERERS);

export const BANNER = (id, target) => `<!-- Generated by pds (${id}${target ? " " + target : ""}). Do not edit: change the records and regenerate. -->\n\n`;

/**
 * Render one view. Throws ViewError with something the author can act on.
 * @param {object} a the analysis from analyse()
 * @param {string} id view id
 * @param {string} [target] element id the view is pointed at
 * @param {{banner?: boolean}} [opts]
 */
export function renderView(a, id, target, opts = {}) {
  const r = RENDERERS[id];
  if (!r) throw new ViewError(`no view ${id}; the views are: ${VIEW_IDS.join(", ")}`);
  const V = bind(a);
  if (target) {
    if (r.none) throw new ViewError(`${id} covers the whole product and takes no target`);
    const el = V.get(target);
    if (!el) {
      const s = suggest(a.model, target);
      throw new ViewError(`no element ${target}${s ? `; did you mean ${s}?` : ""}`);
    }
    if (r.types && !r.types.includes(el.type)) throw new ViewError(`${id} is for ${r.types.join(" or ")}; ${target} is a ${el.type}`);
  } else if (r.required) {
    const example = a.model.all(r.types || undefined)[0]?.id || "<ID>";
    throw new ViewError(`${id} needs an element: pds view ${id} ${example}`);
  }
  const body = r.fn(V, target);
  return (opts.banner ? BANNER(id, target) : "") + body.replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
}

/** Every view `pds views` writes: the product-wide ones, then a specification for each feature and capability. */
export function plan(a) {
  const { model } = a;
  const files = new Map();
  const wide = VIEW_IDS.filter((v) => !["card", "spec"].includes(v));
  for (const id of wide) files.set(`${id}.md`, renderView(a, id, undefined, { banner: true }));
  for (const el of model.all(["CAP", "FEAT"])) {
    if (model.isRetired(el.id)) continue;
    files.set(`specs/${el.id}.md`, renderView(a, "spec", el.id, { banner: true }));
  }
  const rows = wide.map((id) => `| [${a.meta.views.get(id).title}](${id}.md) | ${a.meta.views.get(id).answers} |`);
  const specs = model.all(["CAP", "FEAT"]).filter((e) => !model.isRetired(e.id)).sort((x, y) => x.id.localeCompare(y.id)).map((e) => `- [${e.title}](specs/${e.id}.md) (${e.type === "CAP" ? "capability" : "feature"}, ${a.maturity.get(e.id)?.computed})`);
  files.set("README.md", `${BANNER("index")}# Views\n\nGenerated from the definition. Read them; do not edit them.\n\n| View | Answers |\n| --- | --- |\n${rows.join("\n")}\n\n## Specifications\n\n${specs.join("\n") || "_None yet._"}\n`);
  return files;
}
